#!/usr/bin/env python
"""
scripts/phase2_live_vs_backtest.py — the same events, live vs offline, for 6_rings_trader_2.

Sessions 5 and 6 ran the event bot live (team/trader.py EventTrader, STRATEGY=event).
For each block this reads
  * the LIVE fills from the seat's log ("FILL side qty SYM @ px (fee f)")
  * the recorded tape of that block, replayed offline through EventTrader
    (scripts/phase2_backtest.py's harness: depth-walking fills, 0.30 % fee, halts)
and gives both fill lists to the block's CALENDAR_EVENTs the same way: every fill in
the event's symbols until the next event, marked to the tape mid, fees included.

The live seat carried inventory from earlier blocks, so whole-session P&L is not
comparable to a fresh $150k replay; the per-event trading P&L is.

    python scripts/phase2_live_vs_backtest.py
Output: data/phase2/live_vs_backtest.md, evidence/phase2_live_vs_backtest.txt
"""

from __future__ import annotations

import datetime as dt
import pathlib
import re
import sys
from dataclasses import dataclass

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path[:0] = [str(ROOT / "engine"), str(ROOT)]

import scripts.phase2_backtest as pb               # noqa: E402

BLOCKS = {  # tape → (live log, UTC offset of the log clock)
    "week05": ("logs/6_rings_trader_2_20261029_163731.log", -5),   # CDT
    "week06": ("logs/6_rings_trader_2_20261106_151921.log", -6),   # CST (DST ended Nov 1)
}
FILL_RE = re.compile(r"^(\d\d:\d\d:\d\d) INFO\s+FILL (buy|sell) (\d+) (\S+) @ ([\d.]+) \(fee ([\d.]+)\)")
REJECT_RE = re.compile(r"^(\d\d:\d\d:\d\d) WARNING REJECT #\d+ \[(\w+)\]")


@dataclass
class Fill:
    ts: float
    symbol: str
    side: str
    price: float
    quantity: int
    fee: float


@dataclass
class Event:
    t: float
    pct: float
    symbols: list
    end: float = float("inf")


def read_live(log: pathlib.Path, utc_offset_h: int, lo: float, hi: float) -> tuple[list[Fill], dict]:
    """The live log's fills (and reject counts) inside [lo, hi] epoch seconds."""
    day = re.search(r"_(\d{8})_", log.name).group(1)
    tz = dt.timezone(dt.timedelta(hours=utc_offset_h))
    epoch = lambda hms: dt.datetime.strptime(day + hms, "%Y%m%d%H:%M:%S").replace(tzinfo=tz).timestamp()  # noqa: E731
    fills, rejects = [], {}
    for line in log.read_text(errors="replace").splitlines():
        if (m := FILL_RE.match(line)) and lo <= epoch(m[1]) <= hi:
            fills.append(Fill(epoch(m[1]), m[4], m[2], float(m[5]), int(m[3]), float(m[6])))
        elif (m := REJECT_RE.match(line)) and lo <= epoch(m[1]) <= hi:
            rejects[m[2]] = rejects.get(m[2], 0) + 1
    return fills, rejects


def events_and_mids(path: pathlib.Path) -> tuple[list[Event], dict, float, float]:
    events, mids, ts = [], {}, []
    for r in pb.read_tape(path):
        m, t = r["msg"], float(r["ts"])
        ts.append(t)
        if m.get("type") == "book_snapshot" and m["bids"] and m["asks"]:
            mids.setdefault(m["symbol"], []).append((t, (m["bids"][0][0] + m["asks"][0][0]) / 2))
        elif m.get("event") == "CALENDAR_EVENT":
            events.append(Event(t, float(m["data"]["pct"]), list(m["data"]["affected"])))
    for a, b in zip(events, events[1:]):
        a.end = b.t
    return events, mids, min(ts), max(ts)


def per_event(ev: Event, fills: list, mids: dict) -> dict:
    """Fills, fees, first-fill delay and P&L (cash flow + leftover shares at the mid) of one event."""
    mine = [f for f in fills if f.symbol in ev.symbols and ev.t <= f.ts < ev.end]
    pnl = 0.0
    for s in ev.symbols:
        fs = [f for f in mine if f.symbol == s]
        if fs:
            sign = lambda f: 1 if f.side == "buy" else -1   # noqa: E731
            mark = [m for t, m in mids.get(s, []) if t <= ev.end]
            pnl += sum(-sign(f) * f.price * f.quantity - f.fee for f in fs) \
                + sum(sign(f) * f.quantity for f in fs) * (mark[-1] if mark else 0.0)
    return {"fills": len(mine), "fees": sum(f.fee for f in mine), "pnl": pnl,
            "first": f"{min(f.ts for f in mine) - ev.t:.1f} s" if mine else "—"}


def main() -> int:
    out = ["# Live vs backtest, per event — EventTrader on 6_rings_trader_2 "
           "(generated by scripts/phase2_live_vs_backtest.py)", "",
           "Both sides attributed the same way: every fill in the event's symbols until the next event, "
           "marked to the tape mid; fees included. The live clock is whole seconds.", ""]
    for tape, (log, off) in BLOCKS.items():
        path = ROOT / pb.TAPES[tape]
        events, mids, lo, hi = events_and_mids(path)
        bt, blocked = pb.backtest("event", path)
        live, rejects = read_live(ROOT / log, off, lo, hi)
        out += [f"## {tape} — tape {path.name}, live log {pathlib.Path(log).name}", "",
                "| event | pct | backtest fills | live fills | backtest first fill | live first fill "
                "| backtest fees | live fees | backtest P&L | live P&L |", "|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|"]
        tot = {"b": 0.0, "l": 0.0}
        for ev in events:
            b, l = per_event(ev, bt.fills, mids), per_event(ev, live, mids)
            tot["b"] += b["pnl"]
            tot["l"] += l["pnl"]
            name = ev.symbols[0] if len(ev.symbols) == 1 else "market-wide"
            out.append(f"| t+{ev.t - lo:.0f}s {name} | {ev.pct:+.1%} | {b['fills']} | {l['fills']} | {b['first']} "
                       f"| {l['first']} | {b['fees']:,.0f} | {l['fees']:,.0f} | {b['pnl']:+,.0f} | {l['pnl']:+,.0f} |")
        out += [f"| **total** | | | | | | | | **{tot['b']:+,.0f}** | **{tot['l']:+,.0f}** |", "",
                f"All fills in the block: backtest {len(bt.fills)} (fees {bt.fees:,.0f}), live {len(live)} "
                f"(fees {sum(f.fee for f in live):,.0f}). Live rejects: {rejects or 'none'}. "
                f"Backtest orders blocked by a venue halt: {blocked}.", ""]
    text = "\n".join(out) + "\n"
    pb.OUT.mkdir(parents=True, exist_ok=True)
    (pb.OUT / "live_vs_backtest.md").write_text(text)
    (ROOT / "evidence" / "phase2_live_vs_backtest.txt").write_text(text)
    print(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
